const express = require('express');
const cors = require('cors');
const rateLimit = require('express-rate-limit');
const authRoutes = require('./routes/auth');
const reelRoutes = require('./routes/reels');
const userRoutes = require('./routes/users');
const restaurantRoutes = require('./routes/restaurants');
const categoryRoutes = require('./routes/categories');
const hashtagRoutes = require('./routes/hashtags');
const recipeRoutes = require('./routes/recipes');
const reportRoutes = require('./routes/reports');
const searchRoutes = require('./routes/search');
const exploreRoutes = require('./routes/explore');
const adminRoutes = require('./routes/admin');
const uploadRoutes = require('./routes/upload');
const { uploadDir } = require('./middleware/upload');
const sanitizeInput = require('./middleware/sanitizeInput');
const app = express();
const origins = (process.env.FRONTEND_URL || 'http://localhost:5173,http://localhost:3000').split(',').map(x => x.trim());
app.use(cors({ origin(origin, callback) { if (!origin || origins.includes(origin)) return callback(null, true); callback(new Error('Origin is not allowed by CORS')); }, methods: ['GET', 'POST', 'PATCH', 'DELETE'], allowedHeaders: ['Content-Type', 'Authorization', 'X-Viewer-Session'] }));
app.use(rateLimit({ windowMs: 15 * 60 * 1000, limit: 400, standardHeaders: 'draft-8', legacyHeaders: false }));
app.use(express.json({ limit: '1mb' }));
app.use(sanitizeInput);
app.use('/uploads', express.static(uploadDir, { maxAge: '7d', fallthrough: false }));
app.get('/api/health', (req, res) => res.json({ ok: true, service: 'foodreels-api' }));
app.use('/api/auth', authRoutes); app.use('/api/reels', reelRoutes); app.use('/api/users', userRoutes); app.use('/api/restaurants', restaurantRoutes); app.use('/api/categories', categoryRoutes); app.use('/api/hashtags', hashtagRoutes); app.use('/api/recipes', recipeRoutes); app.use('/api/reports', reportRoutes); app.use('/api/search', searchRoutes); app.use('/api/explore', exploreRoutes); app.use('/api/admin', adminRoutes); app.use('/api/upload', uploadRoutes);
app.use((req, res) => res.status(404).json({ message: 'Route not found' }));
app.use((err, req, res, next) => { console.error(err); const code = err.message === 'Origin is not allowed by CORS' ? 403 : err.status || 500; res.status(code).json({ message: code === 500 ? 'Something went wrong' : err.message }); });
module.exports = app;
